-- =============================================================================
-- Redis 引擎（数据库工作台）—— 数据库变更说明
-- =============================================================================
--
-- 目的
--   veloterm 数据库工作台新增第四个引擎 Redis（crates.io `redis` 1.7.1，
--   tokio-comp + tls-rustls）。本文件说明该接入对 SQLCipher 库
--   （veloterm.db）的表结构影响，并给出核对语句。
--
-- 结论：无需变更
--   零新表、零新列、零迁移。复用既有 db_connections 表：
--     - database      存 Redis 逻辑库，形如 'db0' .. 'dbN'（可空）
--     - service_name  对 Redis 恒为 NULL（该列是 Oracle 服务名专用）
--     - engine        取值新增 'redis'（列为 TEXT，无 CHECK 约束，无需 DDL）
--     - port          表列无默认值；6379 只是表单缺省，直插记录须自带端口
--   老库（已存 mysql / postgres / oracle 记录）无需任何迁移动作，
--   升级后直接可用。
--
-- 执行方式：只读核对
--   以下语句全部是 SELECT，可直接在 SQLCipher 库上跑。注意 veloterm.db 是
--   加密库，需带密钥打开（例如 sqlcipher CLI：PRAGMA key = '<密钥>';），
--   或在应用内以只读方式查看。本文件不含任何写语句。
--
-- =============================================================================


-- -----------------------------------------------------------------------------
-- 1. 核对：Redis 连接记录保存后的形态
-- -----------------------------------------------------------------------------
-- 预期结果（一条 Redis 记录）：
--   engine        = 'redis'
--   port          = 6379（或用户填写的端口）
--   database      = 'db0' .. 'dbN'，或 NULL（= 连接时使用 db0）
--   service_name  = NULL（Redis 不使用该列）
--   ssl_mode      = 'disable' | 'prefer' | 'require' | 'verify-full'
--                   （disable → redis:// 明文；其余三种 → rediss:// TLS）
-- -----------------------------------------------------------------------------
SELECT id, name, engine, host, port, database, service_name, ssl_mode
FROM db_connections
WHERE engine = 'redis';


-- -----------------------------------------------------------------------------
-- 2. 核对：确认没有非 Redis 记录被误改（回归用）
-- -----------------------------------------------------------------------------
-- 升级前后各跑一次，行数与内容应完全一致（Redis 接入只新增记录，
-- 不触碰既有 mysql / postgres / oracle 行）。
-- -----------------------------------------------------------------------------
SELECT engine, COUNT(*) AS n
FROM db_connections
GROUP BY engine
ORDER BY engine;


-- -----------------------------------------------------------------------------
-- 3. 核对：Redis 记录的 database 列取值分布（应为 dbN 或 NULL）
-- -----------------------------------------------------------------------------
-- 若出现纯数字（'0' / '1'）或带斜杠（'db0/foo'）等非约定形态，
-- 说明记录是旧版本/手工插入的，连接层按空值处理（回退 db0）前请先修正。
-- -----------------------------------------------------------------------------
SELECT id, name, database
FROM db_connections
WHERE engine = 'redis'
  AND database IS NOT NULL
  AND database NOT GLOB 'db[0-9]*';


-- =============================================================================
-- 4. 【模板，不要执行】未来若确需加列时的幂等迁移写法
-- =============================================================================
-- 本仓库的列级迁移约定（见 AGENTS.md「存储」节与 src-tauri/src/db.rs）：
-- SQLite 的 ALTER TABLE ADD COLUMN 没有 IF NOT EXISTS，列已存在时报
-- "duplicate column name"；吞掉该错误即幂等——新库建表已含该列时同样走
-- 这条路，因此同一段语句在新库与老库上都能安全执行。
--
-- 用法：新增列时照抄下面一段同构语句，替换列定义与错误前缀即可。
-- 当前 Redis 接入【不需要】执行任何一段。
-- -----------------------------------------------------------------------------
-- ALTER TABLE db_connections ADD COLUMN redis_cluster_mode INTEGER DEFAULT 0;
--
-- 对应的 Rust 侧写法（示意，非本文件内容）：
--   if let Err(e) = conn.execute_batch(
--       "ALTER TABLE db_connections ADD COLUMN redis_cluster_mode INTEGER DEFAULT 0")
--       && !e.to_string().contains("duplicate column")
--   {
--       return Err(format!("failed to apply column migration `redis_cluster_mode`: {e}"));
--   }
--
-- 加列后需同步的四处（漏一处即状态不一致）：
--   1. db.rs 的 CREATE TABLE IF NOT EXISTS db_connections（新库建表）
--   2. db.rs 的幂等 ALTER 批次（老库补列）
--   3. DbConnectionRecord 结构体字段（含 #[serde(default)]）
--   4. 记录 mapper 与 roundtrip 测试
--
-- 另：若加列带默认值且语义上「老记录等价于新默认」，DEFAULT 子句不可省，
-- 否则老行为 NULL，反序列化到非 Option 字段会失败。
-- =============================================================================


-- =============================================================================
-- 备注
-- =============================================================================
-- 1) database 存 'dbN' 文本（如 'db2'），不存裸数字。
-- 2) database 为空 / NULL 时，连接层在建立连接后不执行 SELECT，
--    即使用服务端默认的 db0。这与「显式写 db0」在行为上等价，
--    但记录里保持空值更利于「跟随服务端默认」的语义。
-- 3) service_name 对 Redis 恒为 NULL：该列在 Oracle 引擎下才是必填，
--    Redis 的等价物（逻辑库）放在 database 列。
-- 4) engine 列无枚举约束，新增引擎不需要 DDL；前端下拉与后端引擎分支
--    各自维护取值集合，两处必须同时加 'redis'。
-- =============================================================================
